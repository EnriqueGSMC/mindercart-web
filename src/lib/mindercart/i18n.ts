export type DictKey = keyof typeof DICT.es;

export function t(lang: Language, key: DictKey) {
  return DICT[lang][key] ?? DICT.es[key];
}

export function formatDateTime(ms: number, lang: Language) {
  try {
    return new Intl.DateTimeFormat(lang === "en" ? "en-US" : "es-MX", {
      dateStyle: "short",
      timeStyle: "medium",
    }).format(new Date(ms));
  } catch {
    return new Date(ms).toLocaleString();
  }
}
